def print_dart_map(lang_code, translations):
    """Print translations in Dart map format"""
    print(f"    '{lang_code}': {{")
    for key, value in translations.items():
        # Escape single quotes in the value
        escaped_value = value.replace("'", "\\'")
        print(f"      '{key}': '{escaped_value}',")
    print("    },")

